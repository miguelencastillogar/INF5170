-- INF5170 - Configuración de la tabla para el formulario multipágina.
-- Ejecutar en el SQL Editor del proyecto Supabase asociado a la aplicación.

create table if not exists public.registros_finales (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    nombre varchar(120) not null,
    correo varchar(254) not null,
    telefono varchar(30),
    motivo varchar(30) not null
        check (motivo in ('consulta', 'comentario', 'otro')),
    detalles varchar(2000),
    creado_en timestamptz not null default now()
);

alter table public.registros_finales enable row level security;

-- Permitir insertar únicamente registros vinculados al usuario autenticado.
drop policy if exists "Usuarios autenticados insertan sus propios registros" on public.registros_finales;
create policy "Usuarios autenticados insertan sus propios registros"
on public.registros_finales
for insert
to authenticated
with check (auth.uid() = user_id);

-- Permitir consultar únicamente los registros propios.
drop policy if exists "Usuarios consultan sus propios registros" on public.registros_finales;
create policy "Usuarios consultan sus propios registros"
on public.registros_finales
for select
to authenticated
using (auth.uid() = user_id);

grant select, insert on public.registros_finales to authenticated;
grant usage, select on sequence public.registros_finales_id_seq to authenticated;
